namespace Patched.Service;

/// <summary>
/// PAT-1293. Builds the PowerShell script the one-shot self-update restart task
/// runs: bounces the "Patched Agent" service so <see cref="PendingUpdateApplier"/>
/// — which only ever runs at service START (<c>Worker.ExecuteAsync</c>) — gets a
/// chance to apply a pending self-update marker <see cref="BootstrapUpdater"/> has
/// already staged. See <see cref="PendingUpdateRestartScheduler"/> for how this gets
/// staged and registered, and <c>BootstrapUpdater.cs</c> (PAT-1293) for the fuller
/// account of why this exists at all: BootstrapUpdater discovers a release, downloads
/// it, and writes the marker, but nothing before this ticket ever decided to actually
/// bounce the service — every previously "self-updated" endpoint was in fact bounced
/// by a human during development (PAT-1261, PAT-1269 moved the same wall back
/// without reaching the end of the rail; this closes it).
///
/// Pure string generation, kept separate from <see cref="PendingUpdateRestartScheduler"/>
/// (which does the actual file/schtasks.exe I/O) so the SHAPE of the script is
/// unit-testable on any OS without touching a real Windows service or Task
/// Scheduler — mirrors <see cref="DecommissionHandoffScript"/>'s identical split
/// from <see cref="DecommissionHandoff"/>, for the exact same reason.
///
/// Deliberately much simpler than DecommissionHandoffScript: this script carries no
/// credentials, makes no network call, and only ever restarts a service the marker
/// says is worth restarting for — it either bounces the service or, if the update
/// already applied (marker gone), does nothing but clean up after itself.
/// </summary>
public static class PendingUpdateRestartScript
{
    public static string Build(string taskName, string markerFile, string serviceName)
    {
        // taskName/markerFile/serviceName are interpolated into single-quoted
        // PowerShell strings; all are agent-controlled constants
        // (PathConstants.*, DecommissionHandoffScript.ServiceName), never
        // operator/attacker-controlled input — same defensive-only escaping
        // DecommissionHandoffScript applies to its own agent-controlled constants.
        string escapedTaskName    = taskName.Replace("'", "''");
        string escapedMarkerFile  = markerFile.Replace("'", "''");
        string escapedServiceName = serviceName.Replace("'", "''");

        return $$"""
        # Patched Agent self-update restart — generated by PendingUpdateRestartScheduler
        # (PAT-1293). One-shot, self-deleting: bounces the service so
        # PendingUpdateApplier.Apply() — which only runs at service START — gets a
        # chance to consume a pending self-update marker BootstrapUpdater already
        # staged. Registered by the SERVICE, not the MSI, so the mechanism travels
        # with any build that has it rather than only landing on machines running a
        # brand-new installer (see BootstrapUpdater.cs for the full reasoning).
        $ErrorActionPreference = 'SilentlyContinue'
        $taskName    = '{{escapedTaskName}}'
        $markerFile  = '{{escapedMarkerFile}}'
        $serviceName = '{{escapedServiceName}}'

        # If the marker is already gone, the update it described already applied —
        # either this exact task ran once before and was interrupted after the
        # bounce but before self-deleting (see below), or a normal service restart
        # happened to land in the same window. Either way there is nothing left to
        # do: delete the task and exit WITHOUT touching the service, so a healthy,
        # already-running service is never bounced for no reason.
        if (-not (Test-Path $markerFile)) {
            schtasks.exe /Delete /TN $taskName /F | Out-Null
            exit 0
        }

        Stop-Service -Name $serviceName -Force -ErrorAction SilentlyContinue
        Start-Service -Name $serviceName -ErrorAction SilentlyContinue

        # Self-delete LAST, not first: if this run is interrupted between the
        # service bounce above and reaching this line, the task registration is
        # left in place rather than silently vanishing — visible in Task Scheduler
        # for diagnosis, and (per the marker-gone branch above) safe to leave
        # around even if it never runs again, since a future check on this exact
        # task name would just find the marker gone and clean up harmlessly. Same
        # "delete only once nothing is left to lose" ordering DecommissionHandoffScript
        # uses for its own self-delete.
        schtasks.exe /Delete /TN $taskName /F | Out-Null
        """;
    }
}
