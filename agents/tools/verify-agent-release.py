#!/usr/bin/env python3
"""Verify a Patched agent release asset's HMAC signature and SHA-256 (PAT-507, PAT-892).

Fetches the .hmac signature and SHA256SUMS files from a GitHub release and
verifies the named asset (or a locally-downloaded copy) against both. Run
this before deploying any agent version to an MDM profile or endpoint.

The HMAC-SHA256 signature is the primary check. It is produced by the release
workflow's "Sign artifact with HMAC-SHA256" step (macos-agent-release.yml,
windows-agent-release.yml, release-menubar.yml) using the ARTIFACT_SIGNING_KEY
secret - the same secret an attacker would need in order to forge a release.
SHA256SUMS is kept only as a secondary check: it catches transport corruption,
but it is generated by the same CI run that produced the artifact being
checked, so an attacker who can push a tampered artifact can regenerate a
self-consistent SHA256SUMS to match it. A checksum a build generates about
its own output is not a signature, and verifying only that checksum (as this
tool did before PAT-892) does not detect a compromised release.

You must supply the ARTIFACT_SIGNING_KEY value to verify the signature, via
one of:
  - the ARTIFACT_SIGNING_KEY environment variable, or
  - --key-file PATH pointing at a file containing the key

Never pass the key as a literal --key-style command-line argument. Argument
values are visible to every other process on the host via `ps` and often end
up in shell history - the same class of leak flagged elsewhere in the
2026-07-14 review this fix comes from.

Private GitHub releases require an API token to fetch their release metadata
and assets. Set GITHUB_TOKEN in the environment when verifying from GitHub
Actions or another authorised private-repository context. The token is never
accepted on the command line or printed. Leave it unset for public releases.

Usage - verify a downloaded file against a published release:
    ARTIFACT_SIGNING_KEY=... python3 tools/verify-agent-release.py \\
        --release macos-agent-v0.6.0 \\
        --file patched-agent-macos-0.6.0.tar.gz

Usage - download and verify in one step:
    python3 tools/verify-agent-release.py \\
        --release windows-agent-v0.3.0 \\
        --file PatchedAgent-0.3.0.msi \\
        --download \\
        --key-file /path/to/signing.key

Usage - verify fully offline against local SHA256SUMS and .hmac files:
    python3 tools/verify-agent-release.py \\
        --sums SHA256SUMS \\
        --hmac patched-agent-macos-0.6.0.tar.gz.hmac \\
        --file patched-agent-macos-0.6.0.tar.gz \\
        --key-file /path/to/signing.key

Exit 0 = verified (HMAC signature and checksum both match).
Exit 1 = mismatch, missing signature, or error. Do not deploy on a non-zero exit.
"""

import argparse
import hashlib
import hmac
import os
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

REPO = "Patched-LTD/updater"
GH_RELEASES_API = f"https://api.github.com/repos/{REPO}/releases/tags"
UA = "patched-verify-agent-release/2.0"
SIGNING_KEY_ENV = "ARTIFACT_SIGNING_KEY"
GITHUB_TOKEN_ENV = "GITHUB_TOKEN"
MAX_TEXT_RESPONSE_BYTES = 1 * 1024 * 1024
MAX_ARTIFACT_BYTES = 512 * 1024 * 1024
ARTIFACT_CHUNK_BYTES = 1 * 1024 * 1024


def _github_request(url: str, accept: str) -> urllib.request.Request:
    """Build a GitHub request, using GITHUB_TOKEN only when it is available."""
    headers = {"User-Agent": UA, "Accept": accept}
    github_token = os.environ.get(GITHUB_TOKEN_ENV)
    if github_token:
        headers["Authorization"] = f"Bearer {github_token}"
    return urllib.request.Request(url, headers=headers)


def _response_content_length(response) -> int | None:
    """Return a valid Content-Length if provided, otherwise None."""
    headers = getattr(response, "headers", None)
    raw_length = headers.get("Content-Length") if headers else None
    try:
        content_length = int(raw_length)
    except (TypeError, ValueError):
        return None
    return content_length if content_length >= 0 else None


def _asset_request_error(error: Exception) -> None:
    if isinstance(error, urllib.error.HTTPError):
        sys.exit(f"FATAL: GitHub asset request returned {error.code} - check release access and asset availability")
    sys.exit("FATAL: GitHub asset request failed due to a network, TLS, or timeout error")


def _fetch_text(url: str) -> str:
    """Fetch small release metadata without permitting an unbounded response."""
    req = _github_request(url, "application/octet-stream")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            content_length = _response_content_length(resp)
            if content_length is not None and content_length > MAX_TEXT_RESPONSE_BYTES:
                sys.exit("FATAL: GitHub text asset exceeds the maximum allowed size")
            data = bytearray()
            while len(data) <= MAX_TEXT_RESPONSE_BYTES:
                remaining = MAX_TEXT_RESPONSE_BYTES + 1 - len(data)
                chunk = resp.read(min(64 * 1024, remaining))
                if not chunk:
                    return bytes(data).decode()
                data.extend(chunk)
            sys.exit("FATAL: GitHub text asset exceeds the maximum allowed size")
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError, OSError) as error:
        _asset_request_error(error)


def _fetch_bytes(url: str, dest: Path) -> None:
    """Stream an agent artifact into a sibling temporary file then atomically install it."""
    req = _github_request(url, "application/octet-stream")
    temporary_path: Path | None = None
    try:
        with urllib.request.urlopen(req, timeout=300) as resp:
            content_length = _response_content_length(resp)
            if content_length is not None and content_length > MAX_ARTIFACT_BYTES:
                sys.exit("FATAL: GitHub artifact exceeds the maximum allowed size")

            with tempfile.NamedTemporaryFile(
                mode="wb", dir=dest.parent, prefix=f".{dest.name}.", suffix=".part", delete=False
            ) as temporary_file:
                temporary_path = Path(temporary_file.name)
                bytes_written = 0
                while chunk := resp.read(ARTIFACT_CHUNK_BYTES):
                    bytes_written += len(chunk)
                    if bytes_written > MAX_ARTIFACT_BYTES:
                        sys.exit("FATAL: GitHub artifact exceeds the maximum allowed size")
                    temporary_file.write(chunk)

        os.replace(temporary_path, dest)
        temporary_path = None
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError, OSError) as error:
        _asset_request_error(error)
    finally:
        if temporary_path is not None:
            try:
                temporary_path.unlink(missing_ok=True)
            except OSError:
                pass
    print(f"  Downloaded -> {dest}")


def _digests(key: bytes, path: Path) -> tuple[str, str]:
    """Return (sha256_hex, hmac_sha256_hex) computed in a single pass over path.

    A tarball/MSI can be sizeable; hashing it twice (once for SHA-256, once
    for HMAC-SHA256) would double the disk I/O for no reason, since both
    digests are streamed over the same bytes.
    """
    h = hashlib.sha256()
    mac = hmac.new(key, digestmod=hashlib.sha256)
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
            mac.update(chunk)
    return h.hexdigest().lower(), mac.hexdigest().lower()


def _get_release_assets(tag: str) -> dict[str, str]:
    """Return {filename: download_url} for all assets in the given release tag."""
    url = f"{GH_RELEASES_API}/{tag}"
    req = _github_request(url, "application/vnd.github+json")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            import json
            data = json.loads(resp.read())
    except urllib.error.HTTPError as e:
        sys.exit(f"FATAL: GitHub API returned {e.code} for tag '{tag}' - check the release name")

    # browser_download_url redirects through github.com and can lose the
    # Authorization header. Authenticated private-release verification instead
    # uses the asset API URL, which receives the bearer token directly.
    asset_url_key = "url" if os.environ.get(GITHUB_TOKEN_ENV) else "browser_download_url"
    return {a["name"]: a[asset_url_key] for a in data.get("assets", [])}


def _parse_sums(text: str) -> dict[str, str]:
    """Parse a SHA256SUMS file into {filename: hex_hash}."""
    result = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) == 2:
            result[parts[1].lstrip("*")] = parts[0].lower()
    return result


def _load_signing_key(key_file: str | None) -> bytes | None:
    """Load the ARTIFACT_SIGNING_KEY value from --key-file or the environment.

    Never accepted as a literal command-line value - a secret passed as a
    plain argv value is visible to any other process on the host via `ps`
    and typically lands in shell history, the exact class of leak this
    review flagged. Returns None if no usable (non-empty) key was supplied
    anywhere, so an empty or unreadable --key-file is treated the same as no
    key at all rather than silently verifying against an empty-key HMAC.
    """
    if key_file:
        try:
            raw = Path(key_file).read_bytes()
        except OSError as e:
            sys.exit(f"FATAL: could not read --key-file '{key_file}': {e}")
        key = raw.rstrip(b"\r\n")
        return key if key else None
    env_val = os.environ.get(SIGNING_KEY_ENV)
    if env_val:
        return env_val.encode()
    return None


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Verify a Patched agent release asset's HMAC signature and SHA-256 (PAT-507, PAT-892)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__.split("Usage")[0].strip(),
    )
    ap.add_argument("--release", metavar="TAG",
                    help="GitHub release tag (e.g. macos-agent-v0.6.0)")
    ap.add_argument("--file", required=True, metavar="FILENAME",
                    help="Asset filename to verify (local path or name within the release)")
    ap.add_argument("--download", action="store_true",
                    help="Download the asset before verifying (requires --release)")
    ap.add_argument("--sums", metavar="PATH",
                    help="Local SHA256SUMS file to verify against (alternative to --release)")
    ap.add_argument("--hmac", metavar="PATH",
                    help="Local .hmac signature file to verify against. Required whenever "
                         "--sums is given, so a local checksum override is never silently "
                         "paired with a signature fetched live from --release.")
    ap.add_argument("--key-file", metavar="PATH",
                    help="Path to a file holding the ARTIFACT_SIGNING_KEY value. Alternative to "
                         "the ARTIFACT_SIGNING_KEY environment variable. Never pass the key "
                         "itself as a command-line argument value.")
    args = ap.parse_args()

    if not args.release and not args.sums:
        ap.error("One of --release or --sums is required")
    if args.sums and not args.hmac:
        ap.error("--hmac PATH is required whenever --sums is given - a local SHA256SUMS "
                  "override must not be silently paired with an HMAC signature fetched live "
                  "from --release. Supply both --sums and --hmac locally, or drop --sums and "
                  "let both be fetched from --release.")

    signing_key = _load_signing_key(args.key_file)
    if signing_key is None:
        sys.exit(
            "FATAL: no signing key supplied. The HMAC-SHA256 signature check is the "
            "primary integrity check for a release and cannot be skipped. Supply the "
            f"key via --key-file PATH or the {SIGNING_KEY_ENV} environment variable. "
            "Do not pass it as a plain command-line argument (visible via `ps` / shell history)."
        )

    file_path = Path(args.file)
    target_name = file_path.name

    assets: dict[str, str] = {}
    if args.release:
        assets = _get_release_assets(args.release)

    # ── Fetch or load SHA256SUMS (secondary check - catches transport corruption) ──
    if args.sums:
        sums_text = Path(args.sums).read_text()
        print(f"Using local SHA256SUMS: {args.sums}")
    else:
        if "SHA256SUMS" not in assets:
            sys.exit(f"FATAL: no SHA256SUMS asset found in release '{args.release}'")
        sums_url = assets["SHA256SUMS"]
        print(f"Fetching SHA256SUMS from {sums_url}")
        sums_text = _fetch_text(sums_url)

    sums = _parse_sums(sums_text)
    if not sums:
        sys.exit("FATAL: SHA256SUMS parsed to empty - unexpected format")

    expected_sha256 = sums.get(target_name)
    if expected_sha256 is None:
        print(f"Available entries in SHA256SUMS: {list(sums.keys())}")
        sys.exit(f"FATAL: '{target_name}' not found in SHA256SUMS")

    # ── Fetch or load the HMAC signature (primary check) ──────────────────────────
    hmac_asset_name = f"{target_name}.hmac"
    if args.hmac:
        expected_hmac = Path(args.hmac).read_text().strip().lower()
        print(f"Using local HMAC signature: {args.hmac}")
    else:
        if hmac_asset_name not in assets:
            sys.exit(
                f"FATAL: no '{hmac_asset_name}' asset found in release '{args.release}'. "
                "SHA256SUMS is generated by the same CI run that produced the artifact and "
                "is not a signature - refusing to verify without the real "
                f"{SIGNING_KEY_ENV}-backed HMAC. Do not deploy this release."
            )
        hmac_url = assets[hmac_asset_name]
        print(f"Fetching HMAC signature from {hmac_url}")
        expected_hmac = _fetch_text(hmac_url).strip().lower()

    if not expected_hmac:
        sys.exit(f"FATAL: '{hmac_asset_name}' is empty - refusing to verify against an empty signature")

    # ── Optionally download the asset ──────────────────────────────────────────────
    if args.download:
        if not args.release:
            ap.error("--download requires --release")
        if target_name not in assets:
            sys.exit(f"FATAL: asset '{target_name}' not found in release '{args.release}'")
        if file_path.exists():
            print(f"  File already exists, skipping download: {file_path}")
        else:
            print(f"Downloading {target_name} from release '{args.release}'...")
            _fetch_bytes(assets[target_name], file_path)

    if not file_path.exists():
        sys.exit(f"FATAL: file not found: {file_path}  (use --download to fetch it)")

    # ── Verify HMAC signature (primary) and SHA-256 (secondary) in one pass ────────
    print(f"Computing SHA-256 and HMAC-SHA256 of {file_path} ...")
    actual_sha256, actual_hmac = _digests(signing_key, file_path)

    print(f"  Expected HMAC:    {expected_hmac}")
    print(f"  Actual HMAC:      {actual_hmac}")
    hmac_ok = hmac.compare_digest(actual_hmac, expected_hmac)

    print(f"  Expected SHA-256: {expected_sha256}")
    print(f"  Actual SHA-256:   {actual_sha256}")
    sha256_ok = actual_sha256 == expected_sha256

    if hmac_ok and sha256_ok:
        print(f"\nOK  {target_name} HMAC signature and SHA-256 verified.")
        sys.exit(0)

    if not hmac_ok:
        print(f"\nFAIL  HMAC signature MISMATCH for {target_name} - this artifact was not "
              "signed with the expected key, or has been tampered with. Do not deploy.")
    if not sha256_ok:
        print(f"\nFAIL  SHA-256 MISMATCH for {target_name} - do not deploy this file.")
    sys.exit(1)


if __name__ == "__main__":
    main()
