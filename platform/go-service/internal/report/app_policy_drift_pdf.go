package report

import (
	"bytes"
	"fmt"

	"github.com/go-pdf/fpdf"
)

// RenderAppPolicyDriftPDF renders an App Policy Drift Report PDF.
func RenderAppPolicyDriftPDF(d AppPolicyDriftReport) ([]byte, error) {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(leftMargin, topMargin, rightMargin)
	pdf.SetAutoPageBreak(true, bottomMargin)
	pdf.SetTitle("patched.im: App Policy Drift Report", true)
	pdf.SetAuthor("patched.im", true)
	pdf.SetCreator("patched-api report renderer", true)
	registerReportFont(pdf)

	if err := registerHeader(pdf); err != nil {
		return nil, err
	}

	pdf.SetFooterFunc(func() {
		pdf.SetY(-10)
		pdf.SetFont("Helvetica", "", 8)
		setTextColour(pdf, colourMuted)
		pdf.CellFormat(0, 6, fmt.Sprintf("Page %d / {nb}", pdf.PageNo()), "", 0, "C", false, 0, "")
	})
	pdf.AliasNbPages("")
	pdf.AddPage()

	renderAppPolicyHeader(pdf, d)
	renderAppPolicyTable(pdf, d)
	renderAppPolicyCloser(pdf, d)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("write app policy drift pdf: %w", err)
	}
	return buf.Bytes(), nil
}

func renderAppPolicyHeader(pdf *fpdf.Fpdf, d AppPolicyDriftReport) {
	imageWidth := 80.0
	x := (210.0 - imageWidth) / 2
	pdf.ImageOptions("header.png", x, topMargin, imageWidth, 0, false,
		fpdf.ImageOptions{ImageType: "PNG"}, 0, "")
	pdf.SetY(topMargin + imageWidth*0.6 + 3)

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Endpoint Security  |  Compliance  |  Patch Management",
		"", 1, "C", false, 0, "")
	pdf.Ln(2)
	hrule(pdf, 0.6)

	pdf.Ln(4)
	pdf.SetFont(reportFont, "B", 18)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 10, "App Policy Drift Report", "", 1, "C", false, 0, "")

	pdf.Ln(1)
	pdf.SetFont(reportFont, "", 10)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Prepared for", "", 1, "C", false, 0, "")

	pdf.SetFont(reportFont, "B", 13)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 7, fallback(d.Tenant), "", 1, "C", false, 0, "")

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 5, "Report Date: "+d.GeneratedAt.Format("02 Jan 2006"), "", 1, "C", false, 0, "")
	pdf.CellFormat(0, 5, "Classification: Confidential", "", 1, "C", false, 0, "")
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Prepared by Patched.im Ltd  |  patched.im", "", 1, "C", false, 0, "")

	pdf.Ln(2)
	hrule(pdf, 0.4)
	pdf.Ln(4)
}

func renderAppPolicyTable(pdf *fpdf.Fpdf, d AppPolicyDriftReport) {
	sectionHeader(pdf, "App Policy Drift")
	if len(d.Policies) == 0 {
		pdf.SetFont(reportFont, "I", 9)
		setTextColour(pdf, colourMuted)
		pdf.CellFormat(0, 5, "No app policies defined for this tenant.", "", 1, "L", false, 0, "")
		pdf.Ln(2)
		return
	}

	widths := []float64{55, 40, 45, 34}
	tableHeader(pdf, []string{"App", "Policy", "Enforcement", "Devices With App"}, widths)
	rows := make([][]string, 0, len(d.Policies))
	for _, p := range d.Policies {
		rows = append(rows, []string{
			truncate(p.AppName, 36),
			truncate(p.Policy, 26),
			truncate(p.EnforcementTier, 30),
			fmt.Sprintf("%d", p.DevicesWithApp),
		})
	}
	tableBody(pdf, rows, widths, true)
	pdf.Ln(3)
}

func renderAppPolicyCloser(pdf *fpdf.Fpdf, d AppPolicyDriftReport) {
	pdf.Ln(4)
	hrule(pdf, 0.4)
	pdf.Ln(3)

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourBodyText)
	pdf.MultiCell(0, 4.5,
		"This App Policy Drift Report was generated by Patched.im Ltd from telemetry collected by the patched.im endpoint agent.",
		"", "L", false)

	pdf.Ln(2)
	pdf.SetFont(reportFont, "I", 8)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 4.5,
		"Generated: "+d.GeneratedAt.Format("02 Jan 2006 15:04 MST")+"  |  patched.im",
		"", 1, "L", false, 0, "")
}
