package report

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/go-pdf/fpdf"
)

// RenderBrowserExtensionsPDF renders a Browser Extensions Report PDF.
func RenderBrowserExtensionsPDF(d BrowserExtensionsReport) ([]byte, error) {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(leftMargin, topMargin, rightMargin)
	pdf.SetAutoPageBreak(true, bottomMargin)
	pdf.SetTitle("patched.im: Browser Extensions Report", true)
	pdf.SetAuthor("patched.im", true)
	pdf.SetCreator("patched-api report renderer", true)
	registerReportFont(pdf)

	if err := registerHeader(pdf); err != nil {
		return nil, err
	}

	pdf.SetFooterFunc(func() {
		pdf.SetY(-10)
		pdf.SetFont("Helvetica", "", 8)
		setTextColour(pdf, colourMuted)
		pdf.CellFormat(0, 6, fmt.Sprintf("Page %d / {nb}", pdf.PageNo()), "", 0, "C", false, 0, "")
	})
	pdf.AliasNbPages("")
	pdf.AddPage()

	renderBrowserExtHeader(pdf, d)
	renderBrowserExtKPIBand(pdf, d)
	renderBrowserExtElevated(pdf, d)
	renderBrowserExtAll(pdf, d)
	renderBrowserExtCloser(pdf, d)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("write browser extensions pdf: %w", err)
	}
	return buf.Bytes(), nil
}

func renderBrowserExtHeader(pdf *fpdf.Fpdf, d BrowserExtensionsReport) {
	imageWidth := 80.0
	x := (210.0 - imageWidth) / 2
	pdf.ImageOptions("header.png", x, topMargin, imageWidth, 0, false,
		fpdf.ImageOptions{ImageType: "PNG"}, 0, "")
	pdf.SetY(topMargin + imageWidth*0.6 + 3)

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Endpoint Security  |  Compliance  |  Patch Management",
		"", 1, "C", false, 0, "")
	pdf.Ln(2)
	hrule(pdf, 0.6)

	pdf.Ln(4)
	pdf.SetFont(reportFont, "B", 18)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 10, "Browser Extensions Report", "", 1, "C", false, 0, "")

	pdf.Ln(1)
	pdf.SetFont(reportFont, "", 10)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Prepared for", "", 1, "C", false, 0, "")

	pdf.SetFont(reportFont, "B", 13)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 7, fallback(d.Tenant), "", 1, "C", false, 0, "")

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 5, "Report Date: "+d.GeneratedAt.Format("02 Jan 2006"), "", 1, "C", false, 0, "")
	pdf.CellFormat(0, 5, "Classification: Confidential", "", 1, "C", false, 0, "")
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Prepared by Patched.im Ltd  |  patched.im", "", 1, "C", false, 0, "")

	pdf.Ln(2)
	hrule(pdf, 0.4)
	pdf.Ln(4)
}

func renderBrowserExtKPIBand(pdf *fpdf.Fpdf, d BrowserExtensionsReport) {
	sectionHeader(pdf, "Overview")
	kpiBand(pdf, []kpi{
		{value: fmt.Sprintf("%d", len(d.Extensions)), label: "Total extensions"},
		{value: fmt.Sprintf("%d", d.ElevatedCount), label: "Elevated risk"},
		{value: "—", label: ""},
		{value: "—", label: ""},
	})
	pdf.Ln(3)
}

func renderBrowserExtTable(pdf *fpdf.Fpdf, exts []BrowserExtRow) {
	widths := []float64{48, 22, 20, 18, 66}
	tableHeader(pdf, []string{"Name", "Browser", "Version", "Enabled", "Permissions"}, widths)
	rows := make([][]string, 0, len(exts))
	for _, ext := range exts {
		enabled := "yes"
		if !ext.Enabled {
			enabled = "no"
		}
		perms := joinExtPerms(ext.Permissions, ext.HostPermissions)
		rows = append(rows, []string{
			truncate(ext.Name, 34),
			truncate(ext.Browser, 16),
			truncate(ext.Version, 14),
			enabled,
			truncate(perms, 48),
		})
	}
	tableBody(pdf, rows, widths, true)
	pdf.Ln(3)
}

func renderBrowserExtElevated(pdf *fpdf.Fpdf, d BrowserExtensionsReport) {
	var elevated []BrowserExtRow
	for _, ext := range d.Extensions {
		if strings.EqualFold(ext.RiskLevel, "elevated") {
			elevated = append(elevated, ext)
		}
	}
	if len(elevated) == 0 {
		return
	}
	sectionHeader(pdf, fmt.Sprintf("Elevated Risk Extensions (%d)", len(elevated)))
	renderBrowserExtTable(pdf, elevated)
}

func renderBrowserExtAll(pdf *fpdf.Fpdf, d BrowserExtensionsReport) {
	sectionHeader(pdf, fmt.Sprintf("All Extensions (%d)", len(d.Extensions)))
	if len(d.Extensions) == 0 {
		pdf.SetFont(reportFont, "I", 9)
		setTextColour(pdf, colourMuted)
		pdf.CellFormat(0, 5, "No browser extensions found.", "", 1, "L", false, 0, "")
		pdf.Ln(2)
		return
	}
	renderBrowserExtTable(pdf, d.Extensions)
}

func renderBrowserExtCloser(pdf *fpdf.Fpdf, d BrowserExtensionsReport) {
	pdf.Ln(4)
	hrule(pdf, 0.4)
	pdf.Ln(3)

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourBodyText)
	pdf.MultiCell(0, 4.5,
		"This Browser Extensions Report was generated by Patched.im Ltd from telemetry collected by the patched.im endpoint agent.",
		"", "L", false)

	pdf.Ln(2)
	pdf.SetFont(reportFont, "I", 8)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 4.5,
		"Generated: "+d.GeneratedAt.Format("02 Jan 2006 15:04 MST")+"  |  patched.im",
		"", 1, "L", false, 0, "")
}
