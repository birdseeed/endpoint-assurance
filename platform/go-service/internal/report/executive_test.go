func TestRenderExecutiveSummaryPDF_SmokeTest(t *testing.T) {
	s := fixtureExecutiveSummary()
	s.Recommendations = deriveRecommendations(s)

	pdf, err := RenderExecutiveSummaryPDF(s)
	if err != nil {
		t.Fatalf("RenderExecutiveSummaryPDF: %v", err)
	}
	if len(pdf) < 5000 {
		t.Fatalf("PDF suspiciously small: %d bytes", len(pdf))
	}
	if !strings.HasPrefix(string(pdf[:8]), "%PDF-") {
		t.Errorf("output is not a PDF (first 8 bytes: %q)", pdf[:8])
	}
}

func TestRenderExecutiveSummaryPDF_EmptyEstate(t *testing.T) {
	// Tenant exists but has no devices yet — renderer must not panic and
	// the recommendations must degrade cleanly.
	s := ExecutiveSummary{
		GeneratedAt: time.Now().UTC(),
		Tenant:      "Empty Co",
	}
	s.Recommendations = deriveRecommendations(s)

	pdf, err := RenderExecutiveSummaryPDF(s)
	if err != nil {
		t.Fatalf("RenderExecutiveSummaryPDF on empty estate: %v", err)
	}
	if len(pdf) < 2000 {
		t.Errorf("empty-estate PDF too small: %d bytes", len(pdf))
	}
}

func TestDeriveRecommendations_Coverage(t *testing.T) {
	s := fixtureExecutiveSummary()
	recs := deriveRecommendations(s)

	if len(recs) < 3 {
		t.Errorf("expected at least 3 recommendations, got %d", len(recs))
	}

	// MDM enrolment shows up in TopFailing → recommendation 1 should mention enrolment
	if !strings.Contains(strings.ToLower(recs[0]), "enrol") {
		t.Errorf("first recommendation should mention enrolment, got: %q", recs[0])
	}
	// Last recommendation is always the cadence one
	last := recs[len(recs)-1]
	if !strings.Contains(strings.ToLower(last), "cadence") {
		t.Errorf("last recommendation should mention cadence, got: %q", last)
	}
}

func TestDeriveRecommendations_NoFailures(t *testing.T) {
	// A perfect estate: no top failures, no pending updates, no critical
	// fails. Should still emit at least the cadence recommendation.
	s := ExecutiveSummary{
		GeneratedAt: time.Now().UTC(),
		Tenant:      "Perfect Co",
		Estate:      EstateStats{TotalDevices: 5, MacOSDevices: 5, ActiveLast7d: 5},
		Compliance:  ComplianceStats{OverallPct: 100.0, PassEvaluations: 85, FailEvaluations: 0},
	}
	recs := deriveRecommendations(s)
	if len(recs) == 0 {
		t.Fatal("expected at least the cadence recommendation, got empty slice")
	}
	last := recs[len(recs)-1]
	if !strings.Contains(strings.ToLower(last), "cadence") {
		t.Errorf("cadence recommendation should be present, got last: %q", last)
	}
}

// TestEnabledOSFilter verifies the SQL fragment generated by enabledOSFilter
// for every combination of master-switch state. The fragment is injected into
// the report queries — a wrong value here would silently include/exclude the
// wrong devices from exec-summary reports.
func TestEnabledOSFilter(t *testing.T) {
	tests := []struct {
		sw       platformSwitches
		wantPass []string // substrings that must appear
		wantNone []string // substrings that must NOT appear
	}{
		{
			sw:       platformSwitches{macOSEnabled: true, windowsEnabled: true},
			wantPass: []string{"true"},
			wantNone: []string{"NOT IN"},
		},
		{
			sw:       platformSwitches{macOSEnabled: false, windowsEnabled: true},
			wantPass: []string{"NOT IN", "'macOS'"},
			wantNone: []string{"'Windows'"},
		},
		{
			sw:       platformSwitches{macOSEnabled: true, windowsEnabled: false},
			wantPass: []string{"NOT IN", "'Windows'"},
			wantNone: []string{"'macOS'"},
		},
		{
			sw:       platformSwitches{macOSEnabled: false, windowsEnabled: false},
			wantPass: []string{"NOT IN", "'macOS'", "'Windows'"},
			wantNone: []string{},
		},
	}

	for _, tc := range tests {
		name := "macos=" + boolStr(tc.sw.macOSEnabled) + "_win=" + boolStr(tc.sw.windowsEnabled)
		t.Run(name, func(t *testing.T) {
			got := enabledOSFilter(tc.sw)
			for _, want := range tc.wantPass {
				if !strings.Contains(got, want) {
					t.Errorf("filter %q: want %q, got: %q", name, want, got)
				}
			}
			for _, absent := range tc.wantNone {
				if strings.Contains(got, absent) {
					t.Errorf("filter %q: should not contain %q, got: %q", name, absent, got)
				}
			}
		})
	}
}

func boolStr(b bool) string {
	if b {
		return "on"
	}
	return "off"
}

// TestOSEvaluationDisabled covers the per-row flag used by FetchTenantDevices
// (PAT-745) — the inverse of enabledOSFilter's SQL-layer exclusion, applied
// in Go so devices stay in the roster instead of being hidden.
func TestOSEvaluationDisabled(t *testing.T) {
	tests := []struct {
		name string
		sw   platformSwitches
		os   string
		want bool
	}{
		{"macOS enabled, macOS device", platformSwitches{macOSEnabled: true, windowsEnabled: true}, "macOS", false},
		{"macOS disabled, macOS device", platformSwitches{macOSEnabled: false, windowsEnabled: true}, "macOS", true},
		{"macOS disabled, Windows device unaffected", platformSwitches{macOSEnabled: false, windowsEnabled: true}, "Windows", false},
		{"Windows disabled, Windows device", platformSwitches{macOSEnabled: true, windowsEnabled: false}, "Windows", true},
		{"Windows disabled, macOS device unaffected", platformSwitches{macOSEnabled: true, windowsEnabled: false}, "macOS", false},
		{"both disabled, macOS device", platformSwitches{macOSEnabled: false, windowsEnabled: false}, "macOS", true},
		{"both disabled, Windows device", platformSwitches{macOSEnabled: false, windowsEnabled: false}, "Windows", true},
		{"unknown OS never flagged", platformSwitches{macOSEnabled: false, windowsEnabled: false}, "Linux", false},
		{"empty OS never flagged", platformSwitches{macOSEnabled: false, windowsEnabled: false}, "", false},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := osEvaluationDisabled(tc.sw, tc.os); got != tc.want {
				t.Errorf("osEvaluationDisabled(%+v, %q) = %v, want %v", tc.sw, tc.os, got, tc.want)
			}
		})
	}
}

func TestPluralAndTitleCase(t *testing.T) {
	if plural(1) != "" {
		t.Errorf("plural(1) should be empty, got %q", plural(1))
	}
	if plural(0) != "s" || plural(2) != "s" {
		t.Errorf("plural(0/2) should be 's'")
	}

	if titleCase("critical") != "Critical" {
		t.Errorf("titleCase(critical) = %q, want Critical", titleCase("critical"))
	}
	if titleCase("") != "" {
		t.Errorf("titleCase(empty) should be empty")
	}
	if titleCase("High") != "High" {
		t.Errorf("titleCase already-capitalised should round-trip, got %q", titleCase("High"))
	}
}
