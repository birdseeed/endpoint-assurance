package report

import (
	"bytes"
	"fmt"

	"github.com/go-pdf/fpdf"
)

// RenderDeviceHealthPDF renders a Device Health Report PDF.
func RenderDeviceHealthPDF(d DeviceHealthReport) ([]byte, error) {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(leftMargin, topMargin, rightMargin)
	pdf.SetAutoPageBreak(true, bottomMargin)
	pdf.SetTitle("patched.im: Device Health Report", true)
	pdf.SetAuthor("patched.im", true)
	pdf.SetCreator("patched-api report renderer", true)
	registerReportFont(pdf)

	if err := registerHeader(pdf); err != nil {
		return nil, err
	}

	pdf.SetFooterFunc(func() {
		pdf.SetY(-10)
		pdf.SetFont("Helvetica", "", 8)
		setTextColour(pdf, colourMuted)
		pdf.CellFormat(0, 6, fmt.Sprintf("Page %d / {nb}", pdf.PageNo()), "", 0, "C", false, 0, "")
	})
	pdf.AliasNbPages("")
	pdf.AddPage()

	renderDeviceHealthHeader(pdf, d)
	renderDeviceHealthAttention(pdf, d)
	renderDeviceHealthAll(pdf, d)
	renderDeviceHealthCloser(pdf, d)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("write device health pdf: %w", err)
	}
	return buf.Bytes(), nil
}

func renderDeviceHealthHeader(pdf *fpdf.Fpdf, d DeviceHealthReport) {
	imageWidth := 80.0
	x := (210.0 - imageWidth) / 2
	pdf.ImageOptions("header.png", x, topMargin, imageWidth, 0, false,
		fpdf.ImageOptions{ImageType: "PNG"}, 0, "")
	pdf.SetY(topMargin + imageWidth*0.6 + 3)

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Endpoint Security  |  Compliance  |  Patch Management",
		"", 1, "C", false, 0, "")
	pdf.Ln(2)
	hrule(pdf, 0.6)

	pdf.Ln(4)
	pdf.SetFont(reportFont, "B", 18)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 10, "Device Health Report", "", 1, "C", false, 0, "")

	pdf.Ln(1)
	pdf.SetFont(reportFont, "", 10)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Prepared for", "", 1, "C", false, 0, "")

	pdf.SetFont(reportFont, "B", 13)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 7, fallback(d.Tenant), "", 1, "C", false, 0, "")

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourBodyText)
	pdf.CellFormat(0, 5, "Report Date: "+d.GeneratedAt.Format("02 Jan 2006"), "", 1, "C", false, 0, "")
	pdf.CellFormat(0, 5, "Classification: Confidential", "", 1, "C", false, 0, "")
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 5, "Prepared by Patched.im Ltd  |  patched.im", "", 1, "C", false, 0, "")

	pdf.Ln(2)
	hrule(pdf, 0.4)
	pdf.Ln(4)
}

func renderHealthTable(pdf *fpdf.Fpdf, devs []DeviceHealthRow) {
	widths := []float64{45, 30, 35, 28, 36}
	tableHeader(pdf, []string{"Hostname", "OS", "Battery Condition", "SMART", "Storage Used%"}, widths)
	rows := make([][]string, 0, len(devs))
	for _, dev := range devs {
		bc := "—"
		if dev.BatteryCondition != nil && *dev.BatteryCondition != "" {
			bc = *dev.BatteryCondition
		}
		smart := "—"
		if dev.SMARTStatus != nil && *dev.SMARTStatus != "" {
			smart = *dev.SMARTStatus
		}
		storageUsed := "—"
		if dev.StorageUsedPct != nil {
			storageUsed = fmt.Sprintf("%d%%", *dev.StorageUsedPct)
		}
		rows = append(rows, []string{
			truncate(dev.Hostname, 30),
			truncate(dev.OS, 20),
			truncate(bc, 24),
			truncate(smart, 20),
			storageUsed,
		})
	}
	tableBody(pdf, rows, widths, true)
	pdf.Ln(3)
}

func renderDeviceHealthAttention(pdf *fpdf.Fpdf, d DeviceHealthReport) {
	if len(d.Attention) == 0 {
		return
	}
	sectionHeader(pdf, fmt.Sprintf("Attention Items (%d)", len(d.Attention)))
	renderHealthTable(pdf, d.Attention)
}

func renderDeviceHealthAll(pdf *fpdf.Fpdf, d DeviceHealthReport) {
	if len(d.Devices) == 0 {
		sectionHeader(pdf, "All Devices")
		pdf.SetFont(reportFont, "I", 9)
		setTextColour(pdf, colourMuted)
		pdf.CellFormat(0, 5, "No device health data available.", "", 1, "L", false, 0, "")
		pdf.Ln(2)
		return
	}
	sectionHeader(pdf, fmt.Sprintf("All Devices (%d)", len(d.Devices)))
	renderHealthTable(pdf, d.Devices)
}

func renderDeviceHealthCloser(pdf *fpdf.Fpdf, d DeviceHealthReport) {
	pdf.Ln(4)
	hrule(pdf, 0.4)
	pdf.Ln(3)

	pdf.SetFont(reportFont, "", 9)
	setTextColour(pdf, colourBodyText)
	pdf.MultiCell(0, 4.5,
		"This Device Health Report was generated by Patched.im Ltd from telemetry collected by the patched.im endpoint agent.",
		"", "L", false)

	pdf.Ln(2)
	pdf.SetFont(reportFont, "I", 8)
	setTextColour(pdf, colourMuted)
	pdf.CellFormat(0, 4.5,
		"Generated: "+d.GeneratedAt.Format("02 Jan 2006 15:04 MST")+"  |  patched.im",
		"", 1, "L", false, 0, "")
}
