// TestDetectNewTenantAppsBundlePolicySuppressionDoesNotConsultTeamIDs pins
// the bundle branch's actual precedence contract. candidatesSQL has already
// selected a bundle identity only when the candidate has no usable team ID,
// so suppression is decided solely by the matching bundle policy. Team IDs on
// other policies are irrelevant and must not be compared with an offset into
// the "bundle:<id>" string.
func TestDetectNewTenantAppsBundlePolicySuppressionDoesNotConsultTeamIDs(t *testing.T) {
	pool := naConnectOrSkip(t)
	defer pool.Close()
	ctx := context.Background()

	tenantID := naSeedTenant(t, ctx, pool, "pat1357-bundle-precedence-tenant")
	if _, err := pool.Exec(ctx, `
		INSERT INTO tenant_app_policies
			(tenant_id, team_id, bundle_id, platform, policy, enforcement_tier)
		VALUES
			($1::uuid, NULL, 'com.example.pat1357.covered', 'macos', 'approved', 'report_deploy'),
			-- This is the exact value produced by the old off-by-one
			-- substr('bundle:com.example.pat1357.covered', 6) guard. The
			-- old query therefore skipped the valid bundle policy above;
			-- the corrected bundle branch must ignore this team policy.
			($1::uuid, 'e:com.example.pat1357.covered', NULL, 'macos', 'approved', 'report_deploy'),
			($1::uuid, 'unrelated-team-id', NULL, 'macos', 'approved', 'report_deploy')
	`, tenantID); err != nil {
		t.Fatalf("insert PAT-1357 policies: %v", err)
	}

	naSeedDeviceWithApp(t, ctx, pool, tenantID, "Covered Bundle App", "", "com.example.pat1357.covered")
	naSeedDeviceWithApp(t, ctx, pool, tenantID, "Uncovered Bundle App", "", "com.example.pat1357.uncovered")

	if err := doDetectNewTenantApps(ctx, pool, tenantID, notify.New()); err != nil {
		t.Fatalf("doDetectNewTenantApps: %v", err)
	}
	if naAppIdentityExists(t, ctx, pool, tenantID, "bundle:com.example.pat1357.covered") {
		t.Error("bundle policy did not suppress its matching bundle candidate")
	}
	if !naAppIdentityExists(t, ctx, pool, tenantID, "bundle:com.example.pat1357.uncovered") {
		t.Error("unrelated team policy suppressed an unmatched bundle candidate")
	}
}

// TestDetectNewTenantAppsWindowsAgentSurvivesKeyRegeneration is the
// end-to-end Windows case: a genuinely Windows-tagged device (os =
// "Windows", not the package default macOS) reporting an app whose
// identifier is a ProductCode-style GUID (so candidatesSQL keys it
// "bundle:<guid>", never "name:...") and whose display name is "Patched
// Agent" is suppressed by the seeded name-only policy — and stays
// suppressed after a simulated version bump that changes the GUID, which is
// the entire point of keying this identity on the display name rather than
// the registry uninstall key.
func TestDetectNewTenantAppsWindowsAgentSurvivesKeyRegeneration(t *testing.T) {
	pool := naConnectOrSkip(t)
	defer pool.Close()
	ctx := context.Background()

	tenantID := naSeedTenant(t, ctx, pool, "pat1318-windows-key-regen-tenant")

	// v1: registry key / ProductCode {11111111-2222-3333-4444-555555555501}.
	naSeedDeviceWithAppOS(t, ctx, pool, tenantID, "Patched Agent", "", "{11111111-2222-3333-4444-555555555501}", "Windows")

	notifier := notify.New()
	if err := doDetectNewTenantApps(ctx, pool, tenantID, notifier); err != nil {
		t.Fatalf("doDetectNewTenantApps (v1): %v", err)
	}
	if naAppIdentityExists(t, ctx, pool, tenantID, "bundle:{11111111-2222-3333-4444-555555555501}") {
		t.Error("tenant_new_apps has a row for the Windows Patched Agent (v1 ProductCode) — name-only policy did not suppress it")
	}

	// v2: a version bump regenerates the MSI ProductCode (WiX MajorUpgrade),
	// so the registry key changes even though this is still the same agent.
	// The name-only policy must suppress this new identity too.
	naSeedDeviceWithAppOS(t, ctx, pool, tenantID, "Patched Agent", "", "{11111111-2222-3333-4444-555555555502}", "Windows")
	if err := doDetectNewTenantApps(ctx, pool, tenantID, notifier); err != nil {
		t.Fatalf("doDetectNewTenantApps (v2): %v", err)
	}
	if naAppIdentityExists(t, ctx, pool, tenantID, "bundle:{11111111-2222-3333-4444-555555555502}") {
		t.Error("tenant_new_apps has a row for the Windows Patched Agent (v2 ProductCode, key regenerated) — suppression did not survive the key change")
	}

	var approvedByName bool
	if err := pool.QueryRow(ctx, `
		SELECT EXISTS(
			SELECT 1 FROM tenant_app_policies
			WHERE tenant_id = $1::uuid AND policy = 'approved' AND name = 'Patched Agent' AND platform = 'windows'
		)
	`, tenantID).Scan(&approvedByName); err != nil {
		t.Fatalf("query tenant_app_policies: %v", err)
	}
	if !approvedByName {
		t.Error("tenant_app_policies has no approved, name-keyed row for the Windows \"Patched Agent\" identity")
	}
}

// TestDetectNewTenantAppsMacOSAppNamedPatchedAgentStillQueuedForReview is
// the regression test for PAT-1318 finding A (platform-blind widened
// clause, flagged in adversarial review): a macOS app that happens to
// report the display name "Patched Agent" — with its own team_id, as any
// real macOS app would — must still be queued for review. The seeded
// Windows-scoped name-only policy (platform = 'windows') must NOT suppress
// it just because the names match; only the platform predicate
// (p.platform = d.platform OR p.platform = 'any') on the fourth WHERE NOT
// EXISTS clause in new_apps.go stops that. Without that predicate, any
// endpoint on any platform could self-report an app named "Patched Agent"
// and permanently evade the "for review" queue — a fixed, publicly
// guessable bypass of the only detective control for unknown software.
func TestDetectNewTenantAppsMacOSAppNamedPatchedAgentStillQueuedForReview(t *testing.T) {
	pool := naConnectOrSkip(t)
	defer pool.Close()
	ctx := context.Background()

	tenantID := naSeedTenant(t, ctx, pool, "pat1318-macos-spoof-tenant")

	// naSeedDeviceWithApp defaults to os = "macOS" — deliberately NOT
	// naSeedDeviceWithAppOS here, so this candidate is genuinely
	// platform-derived as macOS by candidatesSQL, exactly like any real
	// macOS endpoint reporting an app under this name would be.
	naSeedDeviceWithApp(t, ctx, pool, tenantID, "Patched Agent", "SPOOFTEAM1318", "com.example.pat1318.spoof")

	notifier := notify.New()
	if err := doDetectNewTenantApps(ctx, pool, tenantID, notifier); err != nil {
		t.Fatalf("doDetectNewTenantApps: %v", err)
	}

	if !naAppIdentityExists(t, ctx, pool, tenantID, "team:spoofteam1318") {
		t.Error("tenant_new_apps has NO row for a macOS app named \"Patched Agent\" — the Windows-scoped name-only policy leaked across platforms (PAT-1318 finding A)")
	}
}

// TestDetectNewTenantAppsNameOnlyPolicySuppressesAnyAppWithThatName names
// the widened semantics directly (PAT-1318): a name-only tenant_app_policies
// row now suppresses review for ANY app with that display name, even one
// that also reports its own team_id/bundle_id and would otherwise be keyed
// "team:"/"bundle:" by candidatesSQL. This is a deliberate breadth increase
// — see the WHERE NOT EXISTS comment in new_apps.go — not a bug: an
// operator who saves a name-only policy for "Some App" is choosing to
// approve that name across identifiers, mirroring mandatoryPolicySatisfiedDrift's
// per-axis matching (app_policy_drift.go) and mandatoryPolicySatisfied's
// (posture.go), which already behave this way for drift/posture.
func TestDetectNewTenantAppsNameOnlyPolicySuppressesAnyAppWithThatName(t *testing.T) {
	pool := naConnectOrSkip(t)
	defer pool.Close()
	ctx := context.Background()

	tenantID := naSeedTenant(t, ctx, pool, "pat1318-name-only-breadth-tenant")

	if _, err := pool.Exec(ctx, `
		INSERT INTO tenant_app_policies (tenant_id, name, platform, policy, enforcement_tier)
		VALUES ($1::uuid, 'Widely Named App', 'any', 'approved', 'report_deploy')
	`, tenantID); err != nil {
		t.Fatalf("insert name-only policy: %v", err)
	}
	t.Cleanup(func() {
		_, _ = pool.Exec(context.Background(), `DELETE FROM tenant_app_policies WHERE tenant_id = $1::uuid`, tenantID)
	})

	// This device_apps row carries its own team_id AND bundle_id — under the
	// old precedence-only matching it would key "team:widelynamedteam" and
	// the name-only policy above would never have been consulted. Under the
	// widened anti-join it is suppressed anyway, because its name matches.
	naSeedDeviceWithApp(t, ctx, pool, tenantID, "Widely Named App", "WidelyNamedTeam", "com.example.widelynamedapp")

	notifier := notify.New()
	if err := doDetectNewTenantApps(ctx, pool, tenantID, notifier); err != nil {
		t.Fatalf("doDetectNewTenantApps: %v", err)
	}

	if naAppIdentityExists(t, ctx, pool, tenantID, "team:widelynamedteam") {
		t.Error("tenant_new_apps has a row for an app whose display name matches a name-only policy — widened name-match suppression did not apply")
	}
}
