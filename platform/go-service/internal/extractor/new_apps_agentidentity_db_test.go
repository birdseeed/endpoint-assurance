// new_apps_agentidentity_db_test.go — PAT-1318 DB-backed regression test:
// a Patched Agent identity (internal/agentidentity) must never surface in
// the "for review" tenant_new_apps queue, on any tenant, on either platform.
// doDetectNewTenantApps now calls agentidentity.EnsurePatchedAgentPolicies
// before running its candidate query, so the seeded 'approved' rows are
// already in place — and already excluded by the anti-join — within the
// very same sweep that would otherwise have flagged them.
//
// The Windows identity is name-only ("Patched Agent", no bundle_id — see
// agentidentity.go's comment on why: the Windows registry uninstall-key
// identifier, ≈ ProductCode, is regenerated by WiX on every release, so it
// is not usable as a stable per-tenant identity). Suppressing it required
// widening candidatesSQL's WHERE NOT EXISTS in new_apps.go with a fourth,
// per-axis, platform-scoped name-match clause (mirroring
// mandatoryPolicySatisfiedDrift in app_policy_drift.go and
// mandatoryPolicySatisfied in posture.go) — previously a name-only policy
// could never suppress anything here, because every real candidate row has
// a non-empty device_apps.identifier (enforced by the tenant_apps CTE),
// which forced app_identity to always be "team:" or "bundle:", never
// "name:". TestDetectNewTenantAppsWindowsAgentSurvivesKeyRegeneration below
// is the test for that case, including across a simulated version bump that
// regenerates the registry key — it seeds a genuinely Windows-tagged device
// (naSeedDeviceWithAppOS, os = "Windows") rather than relying on the
// default macOS device the other tests in this file use, since
// candidatesSQL derives platform from devices.os, not from the app's name
// or identifier shape.
//
// The platform scope on that fourth clause is itself security-relevant, not
// cosmetic: an earlier version of it checked policy_name against the
// candidate's name with no platform predicate at all, so the seeded
// Windows-only "Patched Agent" policy suppressed a candidate of that name
// on ANY platform — any endpoint, including a compromised or malicious one,
// could self-report an app named "Patched Agent" and never appear in the
// review queue, on macOS or Windows. TestDetectNewTenantAppsMacOSAppNamedPatchedAgentStillQueuedForReview
// below is the regression test for exactly that: it is the test that would
// have caught the bug, and it must keep passing.
//
// DB-backed: requires TEST_DATABASE_URL and is skipped otherwise, reusing
// naConnectOrSkip/naSeedTenant/naSeedDeviceWithApp/naSeedDeviceWithAppOS
// (new_apps_notify_test.go, same package) rather than inventing new helpers.

import (
	"context"
	"testing"

	"github.com/jackc/pgx/v5/pgxpool"

	"patched.im/api/internal/notify"
)

// naAppIdentityExists reports whether tenant_new_apps has a row for the
// given tenant + app_identity key (e.g. "bundle:im.patched.updater.menubar").
func naAppIdentityExists(t *testing.T, ctx context.Context, pool *pgxpool.Pool, tenantID, appIdentity string) bool {
	t.Helper()
	var exists bool
	if err := pool.QueryRow(ctx, `
		SELECT EXISTS(
			SELECT 1 FROM tenant_new_apps
			WHERE tenant_id = $1::uuid AND app_identity = $2
		)
	`, tenantID, appIdentity).Scan(&exists); err != nil {
		t.Fatalf("query tenant_new_apps: %v", err)
	}
	return exists
}

// naApprovedBundlePolicyExists reports whether tenant_app_policies has an
// 'approved' row for the given tenant + bundle_id.
func naApprovedBundlePolicyExists(t *testing.T, ctx context.Context, pool *pgxpool.Pool, tenantID, bundleID string) bool {
	t.Helper()
	var exists bool
	if err := pool.QueryRow(ctx, `
		SELECT EXISTS(
			SELECT 1 FROM tenant_app_policies
			WHERE tenant_id = $1::uuid AND policy = 'approved' AND bundle_id = $2
		)
	`, tenantID, bundleID).Scan(&exists); err != nil {
		t.Fatalf("query tenant_app_policies: %v", err)
	}
	return exists
}

func TestDetectNewTenantAppsNeverQueuesPatchedAgentIdentitiesForReview(t *testing.T) {
	pool := naConnectOrSkip(t)
	defer pool.Close()
	ctx := context.Background()

	tenantID := naSeedTenant(t, ctx, pool, "pat1318-suppress-tenant")

	// Both macOS Patched Agent surfaces, installed as a real endpoint would
	// report them. No team_id — the agent isn't Developer-ID signed yet
	// (see agentidentity package doc) — matching the bundle_id-only
	// identity this ticket seeds.
	naSeedDeviceWithApp(t, ctx, pool, tenantID, "Patched Updater", "", "im.patched.updater.menubar")
	naSeedDeviceWithApp(t, ctx, pool, tenantID, "Patched Self Service", "", "im.patched.updater.selfservice")

	// A genuinely unrelated, unpolicied app must still be flagged — proves
	// the sweep suppresses only the seeded Patched Agent identities, not
	// everything.
	naSeedDeviceWithApp(t, ctx, pool, tenantID, "Totally Unrelated App", "TEAM1318CTRL", "com.example.pat1318.control")

	notifier := notify.New()
	if err := doDetectNewTenantApps(ctx, pool, tenantID, notifier); err != nil {
		t.Fatalf("doDetectNewTenantApps: %v", err)
	}

	if naAppIdentityExists(t, ctx, pool, tenantID, "bundle:im.patched.updater.menubar") {
		t.Error("tenant_new_apps has a row for the Patched Agent menu bar app — PAT-1318 auto-approval did not suppress it")
	}
	if naAppIdentityExists(t, ctx, pool, tenantID, "bundle:im.patched.updater.selfservice") {
		t.Error("tenant_new_apps has a row for the Patched Agent Self Service app — PAT-1318 auto-approval did not suppress it")
	}
	if !naAppIdentityExists(t, ctx, pool, tenantID, "team:team1318ctrl") {
		t.Error("tenant_new_apps has NO row for the unrelated control app — sweep suppressed more than the Patched Agent identities")
	}
	if !naApprovedBundlePolicyExists(t, ctx, pool, tenantID, "im.patched.updater.menubar") {
		t.Error("tenant_app_policies has no approved row for im.patched.updater.menubar after the sweep")
	}
	if !naApprovedBundlePolicyExists(t, ctx, pool, tenantID, "im.patched.updater.selfservice") {
		t.Error("tenant_app_policies has no approved row for im.patched.updater.selfservice after the sweep")
	}
}

func TestDetectNewTenantAppsPreservesTypedWindowsWingetIdentity(t *testing.T) {
	pool := naConnectOrSkip(t)
	defer pool.Close()
	ctx := context.Background()
	tenantID := naSeedTenant(t, ctx, pool, "pat1481-new-app-winget-tenant")

	naSeedDeviceWithAppOS(t, ctx, pool, tenantID, "Visual Studio Code", "", "Microsoft.VisualStudioCode", "Windows")
	if _, err := pool.Exec(ctx, `
		UPDATE device_apps SET identifier_kind='winget'
		WHERE device_id IN (SELECT id FROM devices WHERE tenant_id=$1::uuid)
	`, tenantID); err != nil {
		t.Fatalf("type Winget inventory: %v", err)
	}
	if err := doDetectNewTenantApps(ctx, pool, tenantID, notify.New()); err != nil {
		t.Fatalf("doDetectNewTenantApps: %v", err)
	}
	if !naAppIdentityExists(t, ctx, pool, tenantID, "winget:microsoft.visualstudiocode") {
		t.Fatal("typed Windows Winget inventory was not queued with a winget identity")
	}
	if naAppIdentityExists(t, ctx, pool, tenantID, "bundle:microsoft.visualstudiocode") {
		t.Fatal("typed Windows Winget inventory was collapsed to a bundle identity")
	}
}

