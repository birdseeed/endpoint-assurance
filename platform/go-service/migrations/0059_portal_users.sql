-- 0059: customer portal read API (PAT-693).
--
-- Three changes:
--   portal_users       — verified CF Access email → tenant mapping. The ONLY
--                        way a portal identity resolves to a tenant; no
--                        client-supplied tenant identifiers exist anywhere on
--                        the portal surface.
--   portal_access_log  — audit trail of every authenticated portal read
--                        (PAT-330 auth/trust model requires audit-logged reads).
--   report_records.source — distinguishes portal-generated customer reports
--                        from admin/scheduled ones so the portal only lists
--                        and serves its own layout.

BEGIN;

-- ─── portal_users ─────────────────────────────────────────────────────────────
-- email is the PK (stored lowercased; enforced by CHECK) because CF Access
-- asserts exactly one verified email per identity. disabled_at is a soft
-- disable: the row (and its audit trail linkage) survives, but the identity
-- stops resolving. Admin CRUD lives on the internal listener only.
CREATE TABLE portal_users (
    email       TEXT        PRIMARY KEY CHECK (email = lower(email)),
    tenant_id   UUID        NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    disabled_at TIMESTAMPTZ
);

CREATE INDEX idx_portal_users_tenant ON portal_users (tenant_id);

-- ─── portal_access_log ────────────────────────────────────────────────────────
-- One row per authenticated portal request (including denied ones, so a
-- revoked identity probing the surface is visible). tenant_id is nullable:
-- a verified email with no portal_users mapping still gets logged.
CREATE TABLE portal_access_log (
    id           BIGSERIAL   PRIMARY KEY,
    email        TEXT        NOT NULL,
    tenant_id    UUID,
    method       TEXT        NOT NULL DEFAULT '',
    route        TEXT        NOT NULL DEFAULT '',
    status       INT         NOT NULL DEFAULT 0,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_portal_access_log_tenant ON portal_access_log (tenant_id, requested_at DESC);
CREATE INDEX idx_portal_access_log_email  ON portal_access_log (email, requested_at DESC);

-- ─── report_records.source ────────────────────────────────────────────────────
-- 'admin'  — generated via the internal console / scheduler (PAT-370 flow).
-- 'portal' — generated by a customer through POST /v1/portal/reports
--            (customer-layout PDF). The portal lists/downloads ONLY these.
ALTER TABLE report_records
    ADD COLUMN source TEXT NOT NULL DEFAULT 'admin'
    CHECK (source IN ('admin', 'portal'));

CREATE INDEX idx_report_records_source ON report_records (tenant_id, source, created_at DESC);

-- ─── Grants (migration 0057 pattern; enforced by check-grants.sh) ─────────────
GRANT SELECT, INSERT, UPDATE, DELETE ON portal_users      TO patched;
GRANT SELECT, INSERT, UPDATE, DELETE ON portal_access_log TO patched;
GRANT USAGE, SELECT ON SEQUENCE portal_access_log_id_seq  TO patched;

INSERT INTO schema_migrations (version) VALUES ('0059_portal_users')
    ON CONFLICT (version) DO NOTHING;

COMMIT;
