-- patched.im - 0126_report_records_issuance_integrity.sql
-- PAT-1613: issued reports become tamper-evident, frozen evidence.
--
-- The console redesign promises three properties the report pipeline did not
-- have: an issued report carries a verifiable content hash, an issued row
-- cannot be edited after the fact, and a correction is a NEW row linked to the
-- one it replaces rather than an edit of it. This migration adds all three,
-- plus the coverage snapshot that makes "coverage as it was" answerable at all.
--
-- ─── What "issued" means here ────────────────────────────────────────────────
-- A report_records row is INSERTed empty (to claim a UUID for the storage
-- path), then finalised by exactly one UPDATE once the PDF/XLSX bytes are on
-- disk. That finalising UPDATE is the moment the report exists as evidence and
-- becomes downloadable, so that is issuance: handlers.storeReportFiles now sets
-- issued_at in the same statement that sets pdf_path/xlsx_path and the hashes.
--
-- Deliberately NOT keyed on delivery_status = 'sent'. The 0052 delivery
-- lifecycle (pending|sent|failed) was never wired to a mailer: nothing in this
-- repository has ever set 'sent', so a trigger keyed on that transition would
-- be permanently inert while looking healthy - the PAT-912/837/960 shape the
-- root AGENTS.md warns about. Issuance is a property of the artefact, not of a
-- delivery rail that does not exist yet.
--
-- Consequence to know about, recorded here rather than discovered later: this
-- freezes delivery_status at 'pending' and archived at FALSE for every issued
-- row. Both are unwritten today (no mailer; R2 cold-pull is still the 0052
-- TODO). When either rail is built it must record its later event in its own
-- table, not by mutating the evidence row - "evidence and decisions are
-- separate" (repo AGENTS.md). Both are read-only projections of a delivery
-- attempt, and an attempt is not evidence about the estate.
--
-- ─── Hash ────────────────────────────────────────────────────────────────────
-- SHA-256 over the generated bytes, same primitive as device_report_digests
-- (0031). Stored on the row rather than in a side table because a
-- report_records row already IS one issued report. Two columns because a record
-- may hold a PDF, an XLSX, or (when PDF rendering degrades) only the XLSX -
-- one hash column would be NULL for an artefact that actually exists.
--
-- ─── Supersession ────────────────────────────────────────────────────────────
-- A correction is a new row carrying supersedes_report_id. The superseded row
-- then has superseded_by_report_id set once, NULL -> non-NULL, and that single
-- transition is the ONLY mutation an issued row will accept. The guard proves
-- "and nothing else changed" by comparing the whole row minus that one field,
-- so a column added to this table in future is covered by the freeze
-- automatically, with no edit to this function. Whole-row rather than a list of
-- protected columns on purpose: a list silently stops covering the next column
-- someone adds, which is the failure mode this guard exists to prevent.
--
-- No ON DELETE action on either self-reference: the default NO ACTION is
-- checked at end-of-statement, so the tenants ON DELETE CASCADE (which removes
-- a whole supersession chain in one statement) still succeeds. ON DELETE SET
-- NULL would instead have the FK machinery issue an UPDATE against an issued
-- row, which this migration's own trigger would then reject, deadlocking tenant
-- deletion.
--
-- Apply with:
--   psql -h patched-api-01 -U patched -d patched -f migrations/0126_report_records_issuance_integrity.sql
--
-- DEPLOY ORDERING: additive columns + a trigger that only constrains rows with
-- issued_at IS NOT NULL. Every pre-existing row has issued_at NULL, so this is
-- inert on historical data and safe to apply before the Go change ships. Ship
-- the Go change (internal/handlers/report_delivery.go) in the same release so
-- new reports start recording hashes and issuance immediately.

BEGIN;

ALTER TABLE report_records
    ADD COLUMN IF NOT EXISTS pdf_sha256 TEXT,
    ADD COLUMN IF NOT EXISTS xlsx_sha256 TEXT,
    ADD COLUMN IF NOT EXISTS issued_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS coverage_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN IF NOT EXISTS supersedes_report_id UUID REFERENCES report_records(id),
    ADD COLUMN IF NOT EXISTS superseded_by_report_id UUID REFERENCES report_records(id);

-- Lower-case hex SHA-256, or absent. A malformed digest is worse than none:
-- it reads as verifiable evidence and is not.
ALTER TABLE report_records
    DROP CONSTRAINT IF EXISTS report_records_pdf_sha256_hex;
ALTER TABLE report_records
    ADD CONSTRAINT report_records_pdf_sha256_hex
    CHECK (pdf_sha256 IS NULL OR pdf_sha256 ~ '^[0-9a-f]{64}$');

ALTER TABLE report_records
    DROP CONSTRAINT IF EXISTS report_records_xlsx_sha256_hex;
ALTER TABLE report_records
    ADD CONSTRAINT report_records_xlsx_sha256_hex
    CHECK (xlsx_sha256 IS NULL OR xlsx_sha256 ~ '^[0-9a-f]{64}$');

-- A report can neither supersede nor be superseded by itself.
ALTER TABLE report_records
    DROP CONSTRAINT IF EXISTS report_records_no_self_supersession;
ALTER TABLE report_records
    ADD CONSTRAINT report_records_no_self_supersession
    CHECK (supersedes_report_id IS DISTINCT FROM id
       AND superseded_by_report_id IS DISTINCT FROM id);

-- One correction per superseded report: the forward link is a chain, not a fan.
CREATE UNIQUE INDEX IF NOT EXISTS report_records_supersedes_uq
    ON report_records (supersedes_report_id)
    WHERE supersedes_report_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_report_records_issued_at
    ON report_records (tenant_id, issued_at DESC)
    WHERE issued_at IS NOT NULL;

-- ─── Immutability guard ───────────────────────────────────────────────────────
-- Pattern copied from 0111_software_observation_domain.sql
-- (reject_software_observation_update / _truncate), narrowed to rows past
-- issuance so the generation path's single finalising UPDATE still works, and
-- with 0109's hardened search_path so a caller's search_path cannot shadow
-- anything the function resolves.
CREATE OR REPLACE FUNCTION reject_issued_report_record_update() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    -- Still being generated: pdf_path, hashes, coverage and issued_at itself
    -- are all written by the one finalising UPDATE, which runs while the row
    -- is not yet issued.
    IF OLD.issued_at IS NULL THEN
        RETURN NEW;
    END IF;

    -- The single permitted post-issuance mutation: link this row forward to the
    -- report that supersedes it, exactly once, with nothing else changing in
    -- the same statement. Comparing the whole row minus that one field keeps
    -- the check honest as columns are added, and needs no table name, so the
    -- pinned search_path above costs nothing.
    IF OLD.superseded_by_report_id IS NULL
       AND NEW.superseded_by_report_id IS NOT NULL
       AND (to_jsonb(NEW) - 'superseded_by_report_id')
           IS NOT DISTINCT FROM (to_jsonb(OLD) - 'superseded_by_report_id')
    THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'report_records row id=% is issued evidence and is immutable; '
                    'the only permitted change is setting superseded_by_report_id '
                    'once, from NULL, on its own. Record a correction as a new row '
                    'with supersedes_report_id set.', OLD.id
        USING ERRCODE = 'restrict_violation';
END;
$$;

DROP TRIGGER IF EXISTS trg_report_records_reject_issued_update ON report_records;
CREATE TRIGGER trg_report_records_reject_issued_update
    BEFORE UPDATE ON report_records
    FOR EACH ROW EXECUTE FUNCTION reject_issued_report_record_update();

CREATE OR REPLACE FUNCTION reject_report_record_truncate() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    RAISE EXCEPTION 'report_records holds issued report evidence and cannot be truncated'
        USING ERRCODE = 'restrict_violation';
END;
$$;

DROP TRIGGER IF EXISTS trg_report_records_reject_truncate ON report_records;
CREATE TRIGGER trg_report_records_reject_truncate
    BEFORE TRUNCATE ON report_records
    FOR EACH STATEMENT EXECUTE FUNCTION reject_report_record_truncate();

COMMENT ON COLUMN report_records.issued_at IS
    'Set exactly once, when the generated artefact lands on disk. Non-NULL means the row is frozen evidence.';
COMMENT ON COLUMN report_records.pdf_sha256 IS
    'SHA-256 of the stored PDF bytes as generated. Lets an auditor prove the file was not altered after issue.';
COMMENT ON COLUMN report_records.xlsx_sha256 IS
    'SHA-256 of the stored XLSX bytes as generated.';
COMMENT ON COLUMN report_records.coverage_snapshot IS
    'Estate coverage figures as they stood at generation. Frozen so an issued report reads as it did, not as the estate is now.';
COMMENT ON COLUMN report_records.supersedes_report_id IS
    'The earlier report this one corrects. A correction is always a new row, never an edit.';
COMMENT ON COLUMN report_records.superseded_by_report_id IS
    'The correction that replaces this report. The one field an issued row may still have set.';

-- No GRANT needed: this migration only ALTERs an already-granted table and adds
-- indexes and triggers. check-grants.sh requires a grant alongside a newly
-- created table or sequence, and this file creates neither; report_records'
-- privileges were granted by 0052_report_delivery.sql and carry over to columns
-- added later.

